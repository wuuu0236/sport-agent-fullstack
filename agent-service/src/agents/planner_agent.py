"""计划编排 Agent：综合「检索资料 + 训练分析 + 运动知识 + 用户目标」产出周期计划/周报。

创作型角色：本身不搜、不算，只做综合。输入是 Supervisor 喂给它的多源半成品
（研究要点 / 数据分析 / 用户需求），它负责把碎片拼成一份结构化、可执行、口语化的
训练周报或周期计划。资料缺失时如实注明，不编造。

产出类型（周报 / 计划）必须按用户原话切换，不能用一套骨架套所有请求：两者结构
完全不同——周报是「回顾已发生的训练」，计划是「安排未来要练什么」。此前提示词
写死了「生成一份训练计划」，导致「帮我生成周报」最终交出去的标题是
「你的训练计划（修正版）」（2026-09-13 修）。
"""
from .base import BaseAgent
from .. import config, memory

WEEKLY = "weekly"
PLAN = "plan"

# 周报类关键词：用户说了这些，就是要一份对已完成训练的回顾。
# 计划类关键词（计划/方案/课表/安排…）刻意不参与判定——一份周报里
# 也会出现「下周计划」字样，拿它反推会把周报误判成计划。
_WEEKLY_KW = ("周报", "月报", "周报", "报告", "总结", "回顾", "复盘", "汇总")


def deliverable_of(task: str) -> str:
    """判断这次要产出的是「周报」还是「计划」。"""
    t = task or ""
    return WEEKLY if any(k in t for k in _WEEKLY_KW) else PLAN


class PlannerAgent(BaseAgent):
    name = "planner"
    description = "训练计划编排：周期化计划、周报（综合资料+分析+目标）"
    system_prompt = (
        "你是用户的训练编排专家。负责把用户的运动目标、身体限制（如有伤病/体态问题）"
        "与运动科学知识综合成一份结构化、可执行、口语化的文档。\n"
        "产出类型由用户需求决定：要「周报/总结/回顾」就交付一份对已完成训练的回顾，"
        "要「计划/方案/安排」就交付一份未来训练安排——**不要用计划的骨架去套周报**。\n"
        "原则：\n"
        "· 不编造来源和数据；没有外部资料时基于运动科学常识直接给出内容；\n"
        "· 给可量化的安排（距离/配速/组数×次数/心率区间/热量缺口/蛋白质）；\n"
        "· 结合用户画像中的伤病/体态限制，给出动作替换和保护提示；\n"
        "· 结构清晰、口语化、能直接读给用户听。"
    )

    def handle(self, user_msg: str, ctx: dict = None) -> str:
        ctx = ctx or {}
        if config.CONFIG.mock_mode:
            return (
                "📋 计划编排 Agent 已收到请求。\n"
                f"· 用户需求：{user_msg}\n"
                "（离线演示：配置 LLM_API_KEY 后，这里会综合资料+数据+目标生成周报。）"
            )
        # 产出类型以**原始用户任务**为准（ctx["task"]，由 Supervisor._dispatch 传入）：
        # 编排会把 @s1/@s2 的真实产出拼进 user_msg，里面出现「计划」等字样
        # 不能把用户的周报需求带偏。取不到 task（如 /agent/planner 直调）时
        # 退回整段 user_msg 判断。
        kind = deliverable_of(ctx.get("task") or user_msg)
        # 构造明确请求：把用户目标和画像限制一起传给 LLM，
        # 避免模型因"没被提供资料"而迷茫、偶发空回复。
        prompt = self._build_prompt(user_msg, kind)
        return self._llm(prompt, ctx=ctx)

    def _build_prompt(self, user_msg: str, kind: str = PLAN) -> str:
        # 计划必须考虑身体限制——强制全量注入用户画像，不依赖相关性召回。
        # 否则『减脂计划』语义上召回不到『高低肩/膝痛』等关键限制，
        # planner 会误判为『没有提供伤病/体态』而忽略，造成计划回归。
        # （周报同理：解读训练量时必须能对上伤病/体态/睡眠等限制。）
        memory.load()
        items = memory.list_store("user") or []
        profile = "\n".join(f"- {p}" for p in items) if items else "（暂无用户画像记录）"
        head = (
            "请根据以下用户画像和训练数据，生成一份结构化、口语化的**训练周报**。\n\n"
            if kind == WEEKLY else
            "请根据以下用户画像和运动目标，生成一份结构化、可执行的训练计划。\n\n"
        )
        body = (
            "要求：\n"
            "1. 「本期概览」：本期练了几次、总里程/总容量、平均心率/配速/负荷——"
            "只用真实数据，没记录就如实写「本期无记录」，绝不编造数字；\n"
            "2. 「数据解读」：对照时间线/目标，指出进步、停滞或过载风险；\n"
            "3. 「问题诊断」：结合画像里的伤病/体态/睡眠等限制，说明可能原因；\n"
            "4. 「下周建议」：给出可量化的调整（距离/配速/组数×次数/心率区间）；\n"
            "5. 通篇是**回顾已发生的训练**，不要写成未来几周的训练计划表。"
            if kind == WEEKLY else
            "要求：\n"
            "1. 若目标含减脂/增肌，给出热量缺口/盈余、蛋白质建议、有氧安排；\n"
            "2. 若目标含三分化/五分化/全身训练，列出每周分化安排、具体动作、组数×次数；\n"
            "3. 结合画像中的体态问题或伤病，做动作替换或保护提示；\n"
            "4. 所有安排必须量化；结构清晰，用 Markdown 表格/列表呈现；\n"
            "5. 通篇是**未来要练什么**，不要写成对过去训练的回顾。"
        )
        return (
            head +
            f"【用户需求】\n{user_msg}\n\n"
            f"【用户画像（含体态/伤病/心率基线，务必结合，不可忽略）】\n{profile}\n\n"
            + body
        )
