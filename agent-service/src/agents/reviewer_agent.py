"""评审 Agent（Critic）：审查另一个 Agent 的产出质量。

对弈式多 Agent 协作（Generator-Critic）的「审」方：
  - 主循环执行完子任务后，派 reviewer 对最后一个成功产出做反向审查；
  - 审查维度：数据真实性 / 安全红线 / 完整性 / 幻觉；
  - 输出约定：第一行「PASS」= 通过；第一行「ISSUES」= 有问题（后续逐条列问题）；
    评审意见会反馈给生成方重写（主循环控制，最多重写 1 次）。

这是「代码门控模型」在质量维度的延伸：不止拦空输出/跑偏，还拦「答了但答得差」。

**三层加固（2026-09-16，方案 P1-1）**
1. 规则检查前置（`src/review_rules.py`）：空/哨兵/降级/过短这类机械问题由代码直接判
   不过，不再花一次 LLM 调用；疑似编造的数字、缺段落作为「已知疑点」传进来。
2. 结构化清单：原先只说"审查四个维度"，现在要求逐项给出结论（`[OK]`/`[NG]`），
   避免开放式评价退化成"看起来还行"。
3. 换模型评审：`REVIEW_MODEL`（可带 `REVIEW_BASE_URL`/`REVIEW_API_KEY`）配置后，
   评审走另一套模型——消除同模型自评的盲区共享与自我偏好。未配置则回退同模型，
   并在 `agent_done` 事件的 `reviewer_model` 字段如实标注实际调用的模型（不让人
   误以为换了）。
"""
from .base import BaseAgent
from .. import config


class ReviewerAgent(BaseAgent):
    name = "reviewer"
    description = "内容评审：审查 Agent 产出的数据真实性/安全/完整性/幻觉"
    system_prompt = (
        "你是内容评审 Agent（Critic）。负责审查另一个 Agent 的产出，找出问题。\n"
        "你不是作者，不要重写内容，只做判定与指出问题。\n\n"
        "**逐项检查清单（每一项都要给出结论，格式 `[OK] 维度：理由` 或 `[NG] 维度：问题`）**\n"
        "1. 数据准确性：内容里的数据/事实是否与提供的材料一致，有无编造；\n"
        "2. 用户适配：是否结合了用户的伤病/体能/目标限制（比如有伤还建议加大跑量＝不合格）；\n"
        "3. 可操作性：建议是否具体到能照着做（动作/次数/频次/时长），而不是空泛套话；\n"
        "4. 无编造：有无凭空出现的训练记录、事件、来源、数字；\n"
        "5. 完整性：该覆盖的关键部分（结论、数据、建议）是否缺失。\n\n"
        "输出格式（严格）：\n"
        "- 第一行：全项 OK 写 `PASS`；只要有一项 `[NG]` 就写 `ISSUES`。\n"
        "- 第二行起：逐项列出上面五行清单结论；`[NG]` 的项要写清「哪里不对 + 应该怎么改」，"
        "便于生成方据此重写。\n"
        "- 若用户材料里已经给出「规则检查疑点」，必须逐条回应：确认属实就保留并说明，"
        "核对后没问题就写明「已核对，非编造」。"
    )

    def handle(self, user_msg: str, ctx: dict = None) -> str:
        if config.CONFIG.mock_mode:
            return "PASS 评审通过（mock 模式）"
        # 换模型评审：配置了 REVIEW_MODEL 就带上覆盖参数（未配置为空，走默认模型）
        return self._llm(user_msg, ctx=ctx)
